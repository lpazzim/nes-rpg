const FALLBACK = '?';
// letras com acento caem na letra sem acento (os textos do jogo sao sem acento,
// mas assim um acento perdido nao vira "?")
const SEM_ACENTO = { á: 'a', à: 'a', ã: 'a', â: 'a', é: 'e', ê: 'e', í: 'i', ó: 'o', ô: 'o', õ: 'o', ú: 'u', ç: 'c', Á: 'A', Ã: 'A', É: 'E', Í: 'I', Ó: 'O', Õ: 'O', Ú: 'U', Ç: 'C' };

const ORDEM = Object.keys(GLYPHS);
const INDICE = new Map(ORDEM.map((ch, i) => [ch, i]));
const atlasPorCor = new Map();   // cor -> canvas com todos os glifos

/** Escala inteira da fonte para um tamanho pedido em px (1x, 2x ou 3x). */
export function fontScale(size = 8) {
  return Math.max(1, Math.min(3, Math.round(size / 8)));
}

/** Largura que um texto vai ocupar, em pixels. */
export function textWidth(str, size = 8) {
  return str.length * ADVANCE * fontScale(size);
}

/** Altura do corpo das letras (sem a cauda), em pixels. */
export function textHeight(size = 8) {
  return BODY * fontScale(size);
}

// Pinta todos os glifos numa tira horizontal, uma vez por cor.
function atlas(cor) {
  const pronto = atlasPorCor.get(cor);
  if (pronto) return pronto;
  const c = document.createElement('canvas');
  c.width = ORDEM.length * GLYPH_W;
  c.height = GLYPH_H;
  const g = c.getContext('2d');
  g.fillStyle = cor;
  ORDEM.forEach((ch, i) => {
    const linhas = GLYPHS[ch];
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (linhas[y][x] === '#') g.fillRect(i * GLYPH_W + x, y, 1, 1);
      }
    }
  });
  atlasPorCor.set(cor, c);
  return c;
}

function indiceDe(ch) {
  if (INDICE.has(ch)) return INDICE.get(ch);
  const base = SEM_ACENTO[ch];
  if (base && INDICE.has(base)) return INDICE.get(base);
  return INDICE.get(FALLBACK);
}

/**
 * Desenha texto com a fonte bitmap.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x  canto esquerdo (ou centro/direita, conforme align)
 * @param {number} y  base das letras (igual ao fillText)
 * @param {string} color
 * @param {number} size  tamanho pedido em px (vira escala 1x, 2x ou 3x)
 * @param {'left'|'center'|'right'} align
 */
export function drawText(ctx, str, x, y, color, size = 8, align = 'left') {
  const texto = String(str);
  if (!texto) return;
  const s = fontScale(size);
  const img = atlas(color);
  const largura = texto.length * ADVANCE * s;
  let px = Math.round(align === 'center' ? x - largura / 2 : align === 'right' ? x - largura : x);
  const py = Math.round(y) - BODY * s;
  for (const ch of texto) {
    if (ch !== ' ') {
      const i = indiceDe(ch);
      ctx.drawImage(img, i * GLYPH_W, 0, GLYPH_W, GLYPH_H, px, py, GLYPH_W * s, GLYPH_H * s);
    }
    px += ADVANCE * s;
  }
}
